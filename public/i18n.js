  const ORDER = ['en', 'et', 'ru'];
  const SHORT = { en: 'ENG', et: 'EST', ru: 'RUS' };

  function pick() {
    const saved = localStorage.getItem('tesa.lang');
    if (saved && DICT[saved]) return saved;
    const nav = (navigator.language || 'ru').slice(0, 2).toLowerCase();
    return DICT[nav] ? nav : 'ru';
  }

  let LANG = pick();

  function T(key, params) {
    let s = (DICT[LANG] && DICT[LANG][key]);
    if (s == null) s = (DICT.ru[key] != null ? DICT.ru[key] : key);
    if (params) for (const k of Object.keys(params)) s = s.split('{' + k + '}').join(params[k]);
    return s;
  }

  window.I18N = {
    get lang() { return LANG; },
    set lang(v) { if (DICT[v]) { LANG = v; localStorage.setItem('tesa.lang', v); document.documentElement.lang = v; } },
    get locale() { return T('locale'); },
    order: ORDER, short: SHORT, dict: DICT, T,
  };
  window.T = T;
  document.documentElement.lang = LANG;
